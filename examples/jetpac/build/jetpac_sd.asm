@ vpy_update_buttons() — cache buttons (+axes if analog is used)
.global vpy_update_buttons
.type vpy_update_buttons, %function
.thumb_func
vpy_update_buttons:
    push    {r4, lr}
    svc     #14                     @ SYS_READ_BUTTONS_RAW
    mov     r4, r0
    ubfx    r0, r4, #8, #8
    ldr     r1, =BTN_STATE_J1
    str     r0, [r1]
    and     r0, r4, #0xFF
    ldr     r1, =BTN_STATE_J2
    str     r0, [r1]
    svc     #13                     @ SYS_READ_AXES (analog used)
    mov     r4, r0
    ubfx    r0, r4, #24, #8
    sxtb    r0, r0
    ldr     r1, =J1_AXIS_X
    str     r0, [r1]
    ubfx    r0, r4, #16, #8
    sxtb    r0, r0
    ldr     r1, =J1_AXIS_Y
    str     r0, [r1]
    ubfx    r0, r4, #8, #8
    sxtb    r0, r0
    ldr     r1, =J2_AXIS_X
    str     r0, [r1]
    sxtb    r0, r4
    ldr     r1, =J2_AXIS_Y
    str     r0, [r1]
    pop     {r4, pc}
    .ltorg

