    cmp     r7, #0
    beq     dar_init_frame
    subs    r7, r7, #1
    bgt     dar_draw
    ldrb    r8, [r4]                    @ frame_count
    add     r6, r6, #1
    cmp     r6, r8
    blt     dar_no_wrap
    ldrb    r9, [r4, #1]                @ loop flag
    cmp     r9, #0
