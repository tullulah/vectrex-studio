    strb    r7, [r5, #1]
dar_draw_frame:
    ldrb    r8, [r4, #3]                @ frame_table_offset
    lsl     r9, r6, #2
    add     r9, r9, r8
    ldr     r9, [r4, r9]                @ ARM ptr to frame data
