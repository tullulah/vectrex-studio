    mov     r4, r0          @ r4 = instr_ptr
    mov     r5, r1          @ r5 = channel
    mov     r6, r2          @ r6 = note
    @ clamp note to 24-107
    cmp     r6, #24
    it      lt
    movlt   r6, #24
    cmp     r6, #107
    it      gt
    movgt   r6, #107
    @ r7 = &NOTE_STATE[channel]
    ldr     r0, =NOTE_STATE
    mov     r1, #32
    mul     r7, r5, r1
    add     r7, r0, r7
