@ vpy_music_update() — advance PSG music sequencer by one frame
.global vpy_music_update
.type vpy_music_update, %function
.thumb_func
vpy_music_update:
    push    {r4, r5, r6, r7, lr}
    ldr     r0, =PSG_IS_PLAYING
    ldr     r0, [r0]
    cmp     r0, #0
    beq     vmu_done
    ldr     r4, =PSG_DELAY_FRAMES
    ldr     r0, [r4]
    cmp     r0, #0
    beq     vmu_process
    sub     r0, r0, #1
    str     r0, [r4]
    b       vmu_done
vmu_process:
    ldr     r5, =PSG_MUSIC_PTR
    ldr     r5, [r5]
    ldrb    r6, [r5, #1]         @ num_writes
    cmp     r6, #0
    beq     vmu_end
    cmp     r6, #0xFF
    beq     vmu_loop
    add     r7, r5, #2
vmu_write_loop:
    cmp     r6, #0
    beq     vmu_after_writes
    ldrb    r0, [r7]
    ldrb    r1, [r7, #1]
    push    {r6, r7}
    bl      psg_write
    pop     {r6, r7}
    add     r7, r7, #2
    sub     r6, r6, #1
    b       vmu_write_loop
vmu_after_writes:
    ldr     r0, =PSG_MUSIC_PTR
    str     r7, [r0]
    ldrb    r0, [r7]
    str     r0, [r4]
    b       vmu_done
vmu_end:
    bl      vpy_stop_music
    b       vmu_done
vmu_loop:
    ldr     r0, =PSG_MUSIC_START
    ldr     r0, [r0]
    ldr     r1, [r0, #4]         @ loop_event_offset
    add     r1, r0, r1
    ldr     r0, =PSG_MUSIC_PTR
    str     r1, [r0]
    ldrb    r0, [r1]
