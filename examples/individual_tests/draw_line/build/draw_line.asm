@ vpy_draw_vector(r0=asset_ptr, r1=ox, r2=oy)
@ Draws asset at screen position (ox, oy). ox=0, oy=0 = screen centre.
.global vpy_draw_vector
.type vpy_draw_vector, %function
.thumb_func
vpy_draw_vector:
    push    {r4, r5, r6, r7, r8, r9, r10, lr}
    mov     r4, r0              @ asset_ptr
    mov     r9, r1              @ ox
    mov     r10, r2             @ oy
    ldr     r5, [r4]            @ path_count
    mov     r6, #0              @ path index
dvv_pl:
    cmp     r6, r5
    bge     dvv_done
    lsl     r7, r6, #2
    add     r7, r7, #4
    ldr     r7, [r4, r7]
    bl      dv_reset
    ldrb    r0, [r7]
    bl      vpy_set_intensity
    ldrsb   r0, [r7, #2]
    add     r0, r0, r9
    ldrsb   r1, [r7, #1]
    add     r1, r1, r10
    bl      dv_move_to
    add     r8, r7, #5
dvv_cl:
    ldrb    r0, [r8]
    cmp     r0, #0x02
    beq     dvv_cend
    cmp     r0, #0xFF
    bne     dvv_cskip
    ldrsb   r0, [r8, #2]
    ldrsb   r1, [r8, #1]
    bl      dv_draw_delta
    add     r8, r8, #3
    b       dvv_cl
dvv_cskip:
    add     r8, r8, #1
    b       dvv_cl
dvv_cend:
    add     r6, r6, #1
