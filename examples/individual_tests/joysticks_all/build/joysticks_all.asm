.global vpy_draw_circle
.type vpy_draw_circle, %function
.thumb_func
vpy_draw_circle:
    push    {r4, r5, r6, r7, r8, r9, r10, r11, lr}
    sub     sp, sp, #8              @ [sp+0]=first_x [sp+4]=first_y
    mov     r4, r0                  @ cx
    mov     r5, r1                  @ cy
    mov     r6, r2                  @ r6 = radius (the 3rd arg IS the radius, per the API/docs; the old asr#1 halved it → circles came out at half size / dim)
    mov     r7, r3                  @ intensity
    bl      dv_reset
    mov     r0, r7
    bl      vpy_set_intensity
    mov     r0, #0
    bl      vpy_cos
    mul     r0, r0, r6
    mov     r1, #127
    sdiv    r0, r0, r1
    add     r9, r4, r0              @ prev_x = cx + cos(0)*r/127
    mov     r0, #0
    bl      vpy_sin
    mul     r0, r0, r6
    mov     r1, #127
