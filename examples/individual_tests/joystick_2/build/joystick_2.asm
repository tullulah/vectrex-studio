    bge     dvex_done
    ldr     r9, [r4], #4        @ r9 = path data ptr
    ldrb    r10, [r9], #1       @ r10 = path intensity (from .vec)
    ldr     r0, =PITREX_BRIGHTNESS_OVERRIDE
