    str     r1, [r2]            @ PITREX_CUR_Y = target_y
    push    {r0, r1}            @ save call args
    mov     r2, r1              @ trace y
    mov     r1, r0              @ trace x
    ldr     r0, =.Lstr_mv
    bl      uart_trace_xy
    pop     {r0, r1}
    bl      v_directMove32
    mov     r0, #80
    bl      v_setScale
