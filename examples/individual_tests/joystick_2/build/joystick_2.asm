    mov     r0, #10
    mov     r1, #0
    bl      v_writePSG
    ldr     r0, =PSG_SFX_ACTIVE
    mov     r1, #0
    str     r1, [r0]
.Lsfxu_done:
    pop     {r4, r5, r6, r7, pc}
    .ltorg

