.type pitrex_draw_vector_ex, %function
pitrex_draw_vector_ex:
    push    {r4, r5, r6, r7, r8, r9, r10, r11, lr}  @ 36 bytes
    mov     r4, r0              @ asset header ptr
    mov     r5, r1              @ ox
    mov     r6, r2              @ oy
