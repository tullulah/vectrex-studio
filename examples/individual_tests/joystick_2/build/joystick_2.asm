    cmp     r0, #2
    beq     dvex_seg_done
    cmp     r0, #0xFE
    beq     dvex_bezier_seg
    ldrsb   r1, [r9], #1        @ dy
    ldrsb   r0, [r9], #1        @ dx
    cmp     r7, #1
    it      eq
