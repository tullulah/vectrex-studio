    cmp     r0, #0
    movne   r10, r0             @ override from SET_INTENSITY
    ldrsb   r1, [r9], #1        @ r1 = y_start (i8)
    ldrsb   r0, [r9], #1        @ r0 = x_start (i8)
    add     r9, r9, #2          @ skip 2 hdr padding bytes
