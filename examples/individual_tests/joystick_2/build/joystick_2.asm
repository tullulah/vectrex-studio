@ vpy_uart_print_int(r0=val)
.type vpy_uart_print_int, %function
vpy_uart_print_int:
    push    {r4, r5, r6, lr}
    mov     r4, r0
    cmp     r4, #0
    bge     .Lpint_pos
    mov     r0, #'-'
    bl      RPI_AuxUartWrite
    rsb     r4, r4, #0
.Lpint_pos:
    cmp     r4, #0
    bne     .Lpint_nonzero
    mov     r0, #'0'
    bl      RPI_AuxUartWrite
    b       .Lpint_done
.Lpint_nonzero:
    sub     sp, sp, #12
    mov     r6, sp
    mov     r5, #0
.Lpint_extract:
    cmp     r4, #0
    beq     .Lpint_print
    mov     r0, r4
    mov     r1, #10
    bl      __aeabi_idivmod
    add     r1, r1, #'0'
    strb    r1, [r6, r5]
    add     r5, r5, #1
    mov     r4, r0
    b       .Lpint_extract
.Lpint_print:
    sub     r5, r5, #1
.Lpint_ploop:
    cmp     r5, #0
    blt     .Lpint_cleanup
    ldrb    r0, [r6, r5]
    bl      RPI_AuxUartWrite
    sub     r5, r5, #1
    b       .Lpint_ploop
.Lpint_cleanup:
    add     sp, sp, #12
.Lpint_done:
    pop     {r4, r5, r6, pc}

