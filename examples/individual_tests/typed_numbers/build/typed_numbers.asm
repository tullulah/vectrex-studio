    ldr     r9, =LEVEL_DATA_PTR
    ldr     r9, [r9]
    cmp     r9, #0
    beq     .Lul_done
    ldr     r4, =LEVEL_GP_COUNT
    ldr     r4, [r4]            @ r4 = gpCount
    cmp     r4, #0
