    add     r2, r2, r12         @ y += vy
    cmp     r2, r5
    movlt   r2, r5
    movlt   r12, #0
    cmp     r2, r6
    movgt   r2, r6
    movgt   r12, #0
    strh    r1, [r8]            @ buf.x
    strh    r2, [r8, #2]        @ buf.y
    strh    r3, [r8, #4]        @ buf.vx (unchanged)
    strh    r12, [r8, #6]       @ buf.vy
