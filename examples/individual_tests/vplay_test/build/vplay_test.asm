    cmp     r7, #0
    beq     par_init_frame              @ first call: init frame 0
    subs    r7, r7, #1
    bgt     par_draw                    @ still ticking: draw current frame
    ldrb    r8, [r4]                    @ frame_count
    add     r6, r6, #1
    cmp     r6, r8
    blt     par_no_wrap
    ldrb    r9, [r4, #1]                @ loop flag
    cmp     r9, #0
    beq     par_freeze
    mov     r6, #0                      @ loop: wrap to frame 0
