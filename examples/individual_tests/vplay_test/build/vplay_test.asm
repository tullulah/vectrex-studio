@ pitrex_print_number(r0=x, r1=y, r2=value) — print decimal integer
.global pitrex_print_number
.type pitrex_print_number, %function
pitrex_print_number:
    push    {r4, r5, r6, r7, r8, r9, lr}
    mov     r4, r0          @ x
    mov     r5, r1          @ y
    mov     r6, r2          @ value
    sub     sp, sp, #8
    mov     r7, sp          @ buf ptr
    mov     r9, #0          @ is_negative = false
    cmp     r6, #0
    bge     pn_positive
    mov     r9, #1          @ is_negative = true
    mov     r0, #45         @ '-' ASCII (font renders as space-advance)
    strb    r0, [r7]
    add     r7, r7, #1
    rsb     r6, r6, #0      @ abs(r6)
pn_positive:
    @ digit 0: /1000
    ldr     r8, =1000
    mov     r0, r6
    mov     r1, r8
    bl      __aeabi_idivmod  @ r0=quot, r1=rem
    add     r0, r0, #48
    strb    r0, [r7]
    add     r7, r7, #1
    mov     r6, r1
    @ digit 1: /100
    ldr     r8, =100
    mov     r0, r6
    mov     r1, r8
    bl      __aeabi_idivmod  @ r0=quot, r1=rem
    add     r0, r0, #48
    strb    r0, [r7]
    add     r7, r7, #1
    mov     r6, r1
    @ digit 2: /10
    ldr     r8, =10
    mov     r0, r6
    mov     r1, r8
    bl      __aeabi_idivmod  @ r0=quot, r1=rem
    add     r0, r0, #48
    strb    r0, [r7]
    add     r7, r7, #1
    mov     r6, r1
    @ digit 3: ones
    add     r0, r6, #48
    strb    r0, [r7]
    add     r7, r7, #1
    mov     r0, #0
    strb    r0, [r7]
    mov     r0, #0
    mov     r1, #0
    bl      v_directMove32
    ldr     r3, =PITREX_TEXT_SIZE
    ldr     r3, [r3]
    cmp     r3, #0
    it eq
    moveq   r3, #8
    cmp     r9, #0
    beq     pn_print_str
    ldr     r12, =127
    mul     r0, r4, r12         @ x0_px = VPy_x * 127 (Rd≠Rm ✓)
    sub     r2, r5, #8          @ VPy_y - 8 (cap_height offset)
    mul     r1, r2, r12         @ y_baseline_px (Rd≠Rm ✓)
    add     r1, r1, r3, lsl #2  @ + 4*textSize
    add     r1, r1, r3, lsl #1  @ + 2*textSize → y_mid = baseline+6*ts
    add     r2, r0, r3, lsl #3  @ x1 = x0 + 8*textSize
    mov     r3, r1              @ y1 = y0 (horizontal line)
    mov     r12, #0x50
    push    {r12}
    bl      v_directDraw32
    add     sp, sp, #4
    ldr     r3, =PITREX_TEXT_SIZE
    ldr     r3, [r3]
    cmp     r3, #0
    it eq
    moveq   r3, #8
pn_print_str:
    mov     r2, sp          @ buf ptr
pn_lz_scan:
    ldrb    r12, [r2]       @ current char
    cmp     r12, #48        @ '0'?
    bne     pn_lz_done
    ldrb    r12, [r2, #1]   @ peek next char
    cmp     r12, #0         @ last digit — always keep
    beq     pn_lz_done
    add     r2, r2, #1      @ advance past leading '0'
    b       pn_lz_scan
pn_lz_done:
    mov     r0, r4          @ x
    mov     r1, r5          @ y
    sub     r1, r1, #8          @ baseline = top - cap_height (VPy units)
    mov     r12, #127
    mul     r0, r0, r12          @ r0  = x*127
    asr     r0, r0, #7           @ r0  = x*127/128
    mul     r1, r1, r12          @ r1  = y*127
    asr     r1, r1, #7           @ r1  = y*127/128
    mov     r12, #0x50
    push    {r12}
    bl      v_printString
    add     sp, sp, #4
    add     sp, sp, #8
    pop     {r4, r5, r6, r7, r8, r9, pc}
    .ltorg

