    push    {r8, r9}
    ldr     r0, [r9]                    @ ARM ptr to vec data
    mov     r1, r10                     @ ox
    mov     r2, r11                     @ oy
    ldr     r3, =PITREX_ANIM_MIRROR
    ldrb    r3, [r3]                    @ mirror flag
    mov     r8, #127
    push    {r8}                        @ intensity=127
    bl      pitrex_draw_vector_ex
    add     sp, sp, #4                  @ discard intensity
    pop     {r8, r9}
    add     r9, r9, #4                  @ next base_ref ptr
    subs    r8, r8, #1
    bne     par_base_loop
