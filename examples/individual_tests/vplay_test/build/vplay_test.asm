@ pitrex_music_update() — BCM-CLO tempo-stable sequencer
.global pitrex_music_update
.type pitrex_music_update, %function
pitrex_music_update:
    push    {r4, r5, r6, r7, lr}
    ldr     r0, =PSG_IS_PLAYING
    ldr     r0, [r0]
    cmp     r0, #0
    beq     pmu_done
    ldr     r4, =bcm2835_st
    ldr     r4, [r4]
    ldr     r4, [r4, #4]        @ r4 = CLO now
    ldr     r5, =PSG_MUSIC_LAST_CLO
    ldr     r6, [r5]            @ r6 = last CLO (0 if not yet init)
    cmp     r6, #0
    beq     pmu_init_clo
    sub     r6, r4, r6          @ delta_us (wraps correctly)
    ldr     r7, =PSG_MUSIC_TICK_US
    ldr     r0, [r7]
    add     r0, r0, r6
    ldr     r6, =60000
    cmp     r0, r6
    movgt   r0, r6              @ cap
    str     r0, [r7]
    b       pmu_save_clo
pmu_init_clo:
    ldr     r7, =PSG_MUSIC_TICK_US
    mov     r0, #0
    str     r0, [r7]
pmu_save_clo:
    str     r4, [r5]            @ PSG_MUSIC_LAST_CLO = now
pmu_tick_loop:
    ldr     r0, [r7]            @ PSG_MUSIC_TICK_US
    ldr     r6, =20000
    cmp     r0, r6
    blt     pmu_done            @ < 20ms accumulated, nothing to fire
    sub     r0, r0, r6
    str     r0, [r7]  @ consume one tick
    ldr     r4, =PSG_DELAY_FRAMES
    ldr     r0, [r4]
    cmp     r0, #0
    beq     pmu_process
    sub     r0, r0, #1
    str     r0, [r4]
    b       pmu_tick_loop
pmu_process:
    ldr     r5, =PSG_MUSIC_PTR
    ldr     r5, [r5]    @ event ptr
    ldrb    r6, [r5, #1]        @ num_writes
    cmp     r6, #0
    beq     pmu_end
    cmp     r6, #0xFF
    beq     pmu_loop
    add     r7, r5, #2          @ r7 = write pairs (overrides tick_us ptr)
pmu_wl:
    cmp     r6, #0
    beq     pmu_after
    ldrb    r0, [r7]
    ldrb    r1, [r7, #1]
    push    {r6, r7}
    bl      v_writePSG
    pop     {r6, r7}
    add     r7, r7, #2
    sub     r6, r6, #1
    b       pmu_wl
pmu_after:
    ldr     r0, =PSG_MUSIC_PTR
    str     r7, [r0]
    ldr     r4, =PSG_DELAY_FRAMES
    ldrb    r0, [r7]            @ next event delay
    str     r0, [r4]
    ldr     r7, =PSG_MUSIC_TICK_US  @ reload for next tick_loop
    b       pmu_tick_loop
pmu_end:
    bl      pitrex_stop_music
    b       pmu_done
pmu_loop:
    ldr     r0, =PSG_MUSIC_START
    ldr     r0, [r0]
    ldr     r1, [r0, #4]        @ loop_event_byte_offset
    add     r1, r0, r1
    ldr     r0, =PSG_MUSIC_PTR
    str     r1, [r0]
    ldr     r4, =PSG_DELAY_FRAMES
    ldrb    r0, [r1]
    str     r0, [r4]
    ldr     r7, =PSG_MUSIC_TICK_US  @ reload for next tick_loop
    b       pmu_tick_loop
pmu_done:
    pop     {r4, r5, r6, r7, pc}
    .ltorg

