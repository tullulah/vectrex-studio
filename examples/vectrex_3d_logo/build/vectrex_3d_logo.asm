@ vpy_move(r0=x, r1=y) — position beam (absolute from current)
.global vpy_move
.type vpy_move, %function
.thumb_func
vpy_move:
    push    {r4, r5, lr}
    mov     r4, r0
    mov     r5, r1
    ldr     r0, =VPY_MOVE_X
    str     r4, [r0]            @ VPY_MOVE_X = x
    str     r5, [r0, #4]        @ VPY_MOVE_Y = y  (VPY_MOVE_Y = VPY_MOVE_X + 4)
    mov     r0, #0xD001
    mov     r1, r5
    bl      bus_write
    mov     r0, #0xD000
    mov     r1, #0x00
    bl      bus_write
    mov     r0, #0xD001
    mov     r1, r4
    bl      bus_write
    mov     r0, #0xD000
    mov     r1, #0x01
    bl      bus_write
    pop     {r4, r5, pc}
    .ltorg

@ vpy_draw_line(r0=x0, r1=y0, r2=x1, r3=y1, [sp+0]=intensity)
@ Splits segments longer than 127 units using SDIV for proportional steps
.global vpy_draw_line
.type vpy_draw_line, %function
.thumb_func
vpy_draw_line:
    push    {r4, r5, r6, r7, r8, lr}
    mov     r4, r0
    mov     r5, r1
    mov     r6, r2
    mov     r7, r3
    ldr     r2, =VPY_MOVE_X
    ldr     r3, [r2]            @ r3 = VPY_MOVE_X
    ldr     r2, [r2, #4]        @ r2 = VPY_MOVE_Y
    add     r4, r4, r3          @ x0 += MOVE_X
    add     r5, r5, r2          @ y0 += MOVE_Y
    add     r6, r6, r3          @ x1 += MOVE_X
    add     r7, r7, r2          @ y1 += MOVE_Y
    ldr     r8, [sp, #24]           @ intensity (5th arg, past 6 saved regs)
    bl      dv_reset
    mov     r0, r8
    bl      vpy_set_intensity
    mov     r0, r4
    mov     r1, r5
    bl      dv_move_to
    sub     r4, r6, r4
    sub     r5, r7, r5
    movs    r6, r4
    bpl     vdl_dx_pos
    neg     r6, r4
vdl_dx_pos:
    movs    r7, r5
    bpl     vdl_dy_pos
    neg     r7, r5
vdl_dy_pos:
    cmp     r6, r7
    it      ge
    movge   r7, r6
    cmp     r7, #0
    beq     vdl_done
    add     r7, r7, #126
    mov     r6, #127
    sdiv    r8, r7, r6
vdl_loop:
    cmp     r8, #0
    beq     vdl_done
    sdiv    r0, r4, r8
    sdiv    r1, r5, r8
    sub     r4, r4, r0
    sub     r5, r5, r1
    sub     r8, r8, #1
    bl      dv_draw_delta
    b       vdl_loop
vdl_done:
    pop     {r4, r5, r6, r7, r8, pc}
    .ltorg

@ vpy_draw_vector_ex(r0=asset, r1=ox, r2=oy, r3=mirror, [sp+0]=intensity)
@ Draws asset centered at (ox,oy); mirror: bit0=flipX, bit1=flipY
@ dv_reset called before EVERY path so each path starts from screen centre.
.global vpy_draw_vector_ex
.type vpy_draw_vector_ex, %function
.thumb_func
vpy_draw_vector_ex:
    push    {r4, r5, r6, r7, r8, r9, r10, lr}
    mov     r4, r0              @ asset_ptr
    mov     r9, r1              @ ox  (kept for whole function)
    mov     r10, r2             @ oy  (kept for whole function)
    mov     r7, r3              @ mirror
    ldr     r8, [sp, #32]       @ intensity arg (8 saved regs = 32 bytes)
    ldr     r5, [r4]            @ path_count
    mov     r6, #0              @ path_idx
dvex_pl:
    cmp     r6, r5
    bge     dvex_done
    lsl     r3, r6, #2
    add     r3, r3, #4
    ldr     r3, [r4, r3]
    bl      dv_reset
    ldrb    r0, [r3]            @ .vec per-path intensity
    cmp     r8, #0
    it      ne
    movne   r0, r8             @ if intensity arg != 0, use it
    bl      vpy_set_intensity
    ldrsb   r0, [r3, #2]        @ x_start
    ldrsb   r1, [r3, #1]        @ y_start
    tst     r7, #1
    beq     dvex_nfx
    neg     r0, r0
dvex_nfx:
    tst     r7, #2
    beq     dvex_nfy
    neg     r1, r1
dvex_nfy:
    add     r0, r0, r9          @ x_start + ox
    add     r1, r1, r10         @ y_start + oy
    bl      dv_move_to
    add     r2, r3, #5          @ command ptr
dvex_cl:
    ldrb    r0, [r2]
    cmp     r0, #0x02
    beq     dvex_cend
    cmp     r0, #0xFF
    bne     dvex_cskip
    ldrsb   r0, [r2, #2]        @ dx
    ldrsb   r1, [r2, #1]        @ dy
    tst     r7, #1
    beq     dvex_nfx2
    neg     r0, r0
dvex_nfx2:
    tst     r7, #2
    beq     dvex_nfy2
    neg     r1, r1
dvex_nfy2:
    bl      dv_draw_delta
    add     r2, r2, #3
    b       dvex_cl
dvex_cskip:
    add     r2, r2, #1
    b       dvex_cl
dvex_cend:
    add     r6, r6, #1
    b       dvex_pl
dvex_done:
    pop     {r4, r5, r6, r7, r8, r9, r10, pc}
    .ltorg

@ vpy_draw_circle(r0=cx, r1=cy, r2=radius, r3=intensity)
@ 16-segment circle via sin/cos LUT
.global vpy_draw_circle
.type vpy_draw_circle, %function
.thumb_func
vpy_draw_circle:
    push    {r4, r5, r6, r7, r8, r9, r10, r11, lr}
    sub     sp, sp, #8              @ [sp+0]=first_x [sp+4]=first_y
    mov     r4, r0                  @ cx
    mov     r5, r1                  @ cy
    asr     r6, r2, #1              @ r6 = diam/2 = radius (matches M6809 convention)
    mov     r7, r3                  @ intensity
    bl      dv_reset
    mov     r0, r7
    bl      vpy_set_intensity
    mov     r0, #0
    bl      vpy_cos
    mul     r0, r0, r6
    mov     r1, #127
    sdiv    r0, r0, r1
    add     r9, r4, r0              @ prev_x = cx + cos(0)*r/127
    mov     r0, #0
    bl      vpy_sin
    mul     r0, r0, r6
    mov     r1, #127
    sdiv    r0, r0, r1
    add     r10, r5, r0             @ prev_y = cy + sin(0)*r/127
    str     r9, [sp]
    str     r10, [sp, #4] @ save first point
    mov     r0, r9
    mov     r1, r10
    bl      dv_move_to
    mov     r8, #1
vpy_dc_loop:
    cmp     r8, #16
    bge     vpy_dc_close
    lsl     r0, r8, #3
    bl      vpy_cos
    mul     r0, r0, r6
    mov     r1, #127
    sdiv    r0, r0, r1
    add     r11, r4, r0             @ new_x
    lsl     r0, r8, #3
    bl      vpy_sin
    mul     r0, r0, r6
    mov     r1, #127
    sdiv    r0, r0, r1
    add     r0, r5, r0              @ new_y in r0
    sub     r2, r11, r9             @ dx = new_x - prev_x
    sub     r3, r0, r10             @ dy = new_y - prev_y
    mov     r9, r11                 @ prev_x = new_x
    mov     r10, r0                 @ prev_y = new_y
    mov     r0, r2
