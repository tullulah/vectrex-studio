@ vpy_wait_recal() — wait for VIA Timer 1 (frame sync)
.global vpy_wait_recal
.type vpy_wait_recal, %function
.thumb_func
vpy_wait_recal:
    push    {lr}
    mov     r0, #0xD006
    mov     r1, #0x7F
    bl      bus_write
    mov     r0, #0xD007
    mov     r1, #0x00
    bl      bus_write
    mov     r0, #0xD005
    mov     r1, #0x00
    bl      bus_write
vpy_wr_poll:
    mov     r0, #0xD00D
    bl      bus_read
    tst     r0, #0x40
    beq     vpy_wr_poll
    mov     r0, #0xD004
    bl      bus_read
    pop     {pc}
    .ltorg

