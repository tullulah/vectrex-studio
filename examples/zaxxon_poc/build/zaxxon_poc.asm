@ vpy_audio_update() — advance SFX sequencer by one frame
.global vpy_audio_update
.type vpy_audio_update, %function
.thumb_func
vpy_audio_update:
    push    {r4, r5, r6, r7, lr}
    ldr     r0, =PSG_SFX_ACTIVE
    ldr     r0, [r0]
    cmp     r0, #0
    beq     vau_done
    ldr     r4, =PSG_SFX_DELAY
    ldr     r0, [r4]
    cmp     r0, #0
    beq     vau_proc
    sub     r0, r0, #1
    str     r0, [r4]
    b       vau_done
vau_proc:
    ldr     r5, =PSG_SFX_PTR
    ldr     r5, [r5]
    ldrb    r6, [r5, #1]         @ num_writes
    cmp     r6, #0
    beq     vau_end
    add     r7, r5, #2
vau_wl:
    cmp     r6, #0
    beq     vau_aw
    ldrb    r0, [r7]
    ldrb    r1, [r7, #1]
    cmp     r0, #7
    bne     vau_do_write
    push    {r1, r6, r7}    @ save sfx_mixer, loop vars
    bl      psg_read         @ r0=7 already → returns Regs[7]
    pop     {r1, r6, r7}    @ restore sfx_mixer to r1; r0=cur_mixer
    and     r0, r0, #0xDB   @ keep non-C bits from music (0xDB=~0x24)
    and     r1, r1, #0x24   @ keep only C bits from SFX
    orr     r1, r0, r1      @ r1 = merged mixer
    mov     r0, #7          @ reg = 7
vau_do_write:
    push    {r6, r7}
    bl      psg_write
    pop     {r6, r7}
    add     r7, r7, #2
    sub     r6, r6, #1
    b       vau_wl
vau_aw:
    ldr     r0, =PSG_SFX_PTR
    str     r7, [r0]
    ldrb    r0, [r7]
    str     r0, [r4]
    b       vau_done
vau_end:
    ldr     r0, =PSG_SFX_ACTIVE
    mov     r1, #0
    str     r1, [r0]
vau_done:
    pop     {r4, r5, r6, r7, pc}
    .ltorg

