def scale(pt, half=0, shift=0):
    x, y = pt
    # glyph body 9x11 inside the 16px cell — adjacent characters need air,
    # at full cell width they read as one clump
    px = 3 + (x * 3) // 2
    if half:
        px = 1 + x  # half-width variant for composite tiles
    return (px + shift, 2 + (y * 11) // 8)


def main():
    pts, entries = [], {}

    def emit(strokes, half=0, shift=0):
        first = len(pts)
        for s in strokes:
            for i, p in enumerate(s):
                x, y = scale(p, half, shift)
                pts.append((x, y, 1 if i == 0 else 0))
        return (first, len(pts) - first)

    for ch, strokes in G.items():
        entries[ord(ch)] = emit(strokes)

    # composite tiles: two half-width glyphs side by side in one cell
    for code, txt in {0x5B: '1P', 0x5C: '2P', 0x5D: 'HI'}.items():
        first = len(pts)
        for i, ch in enumerate(txt):
            emit(G[ch], half=1, shift=i * 7)
        entries[code] = (first, len(pts) - first)

    out = ['/* generated by tools/make_font.py — do not edit */']
    out.append('static const unsigned char sb_font_pts[][3] = {')
    for x, y, pen in pts:
        out.append(f' {{{x},{y},{pen}}},')
    out.append('};')
    out.append('/* index by (code - 0x20) for codes 0x20-0x5f; count 0 = blank */')
    out.append('static const struct { unsigned short first, count; } sb_font_idx[0x40] = {')
    for code in range(0x20, 0x60):
        f, c = entries.get(code, (0, 0))
        label = chr(code) if 0x20 < code < 0x5B else {0x5B: '1P', 0x5C: '2P', 0x5D: 'HI'}.get(code, ' ')
        out.append(f' {{{f},{c}}}, /* {label} */')
    out.append('};')

    Path(__file__).resolve().parent.parent.joinpath('src/sb_font.h').write_text('\n'.join(out) + '\n')
    print(f'src/sb_font.h: {len(entries)} glyph entries, {len(pts)} points')


if __name__ == '__main__':
    main()
