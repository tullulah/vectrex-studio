#!/usr/bin/env python3
"""Generate src/sb_font.h — a compact stroke font for the game's text tiles.

The game writes text straight into Pandora RAM as ASCII tile codes (0x20-0x5a),
plus a bold digit set at 0x04-0x0d and three composite tiles (1P / 2P / HI).
Instead of tracing ~90 raster tiles, every text tile renders as a few vector
strokes from this original single-stroke font.

Glyphs are authored on a 6x8 grid (y down) and pre-scaled here to pixel
coordinates inside a 16px tile: x -> 2 + gx*2 (2..14), y -> 1 + gy*13/8.
Header layout: packed points (x,y,penup) per glyph + an index by ASCII code.
"""
