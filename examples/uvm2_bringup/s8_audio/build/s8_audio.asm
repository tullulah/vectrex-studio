@ vpy_draw_line(r0=x0, r1=y0, r2=x1, r3=y1, [sp+0]=intensity)
@ Splits segments longer than 127 units using SDIV for proportional steps
.global vpy_draw_line
.type vpy_draw_line, %function
.thumb_func
vpy_draw_line:
    push    {r4, r5, r6, r7, r8, lr}
    mov     r4, r0
    mov     r5, r1
    mov     r6, r2
    mov     r7, r3
    ldr     r2, =VPY_MOVE_X
    ldr     r3, [r2]            @ r3 = VPY_MOVE_X
    ldr     r2, [r2, #4]        @ r2 = VPY_MOVE_Y
    add     r4, r4, r3          @ x0 += MOVE_X
    add     r5, r5, r2          @ y0 += MOVE_Y
    add     r6, r6, r3          @ x1 += MOVE_X
    add     r7, r7, r2          @ y1 += MOVE_Y
    ldr     r8, [sp, #24]           @ intensity (5th arg, past 6 saved regs)
    bl      dv_reset
    mov     r0, r8
    bl      vpy_set_intensity
    mov     r0, r4
    mov     r1, r5
    bl      dv_move_to
    sub     r4, r6, r4
    sub     r5, r7, r5
    movs    r6, r4
    bpl     vdl_dx_pos
    neg     r6, r4
vdl_dx_pos:
    movs    r7, r5
    bpl     vdl_dy_pos
    neg     r7, r5
vdl_dy_pos:
    cmp     r6, r7
    it      ge
    movge   r7, r6
    cmp     r7, #0
    beq     vdl_done
    add     r7, r7, #126
    mov     r6, #127
    sdiv    r8, r7, r6
vdl_loop:
    cmp     r8, #0
    beq     vdl_done
    sdiv    r0, r4, r8
    sdiv    r1, r5, r8
    sub     r4, r4, r0
    sub     r5, r5, r1
    sub     r8, r8, #1
    bl      dv_draw_delta
    b       vdl_loop
vdl_done:
    pop     {r4, r5, r6, r7, r8, pc}
